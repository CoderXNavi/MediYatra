export function getTranslation(lang, key) {
  const selectedDict = TRANSLATIONS[lang] || TRANSLATIONS.EN;
  return selectedDict[key] || TRANSLATIONS.EN[key] || key;
}

export function triggerGlobalWebsiteTranslation(langCode) {
  const code = (langCode || 'EN').toLowerCase();
  
  try {
    // 1. Set Google Translate Cookie
    document.cookie = `googtrans=/en/${code}; path=/; domain=${window.location.hostname}`;
    document.cookie = `googtrans=/en/${code}; path=/;`;

    // 2. Trigger Google Translate combo dropdown
    const combo = document.querySelector('.goog-te-combo');
    if (combo) {
      combo.value = code;
      combo.dispatchEvent(new Event('change'));
    }
  } catch (e) {
    console.warn('Translate trigger exception:', e);
  }

  // 3. Update document orientation (RTL for Arabic)
  if (code === 'ar') {
    document.documentElement.dir = 'rtl';
    document.documentElement.lang = 'ar';
  } else {
    document.documentElement.dir = 'ltr';
    document.documentElement.lang = code;
  }
}
